import fs from "node:fs";
import path from "node:path";

export const VITE_OVERLAY_FILE = ".vercio.vite.config.mjs";

const VITE_CONFIG_FILES = [
  "vite.config.ts",
  "vite.config.mts",
  "vite.config.js",
  "vite.config.mjs",
  "vite.config.cjs",
  "vite.config.cts",
];

export function findViteConfig(dir) {
  for (const name of VITE_CONFIG_FILES) {
    if (fs.existsSync(path.join(dir, name))) return name;
  }
  return null;
}

/**
 * True when the package script runs the plain Vite CLI, so appending
 * `--config <overlay>` cannot break a framework wrapper (e.g. `remix vite:dev`)
 * or replace a config/root the script already chose itself.
 */
export function supportsViteConfigOverlay(scriptCommand) {
  const value = String(scriptCommand || "").trim();
  if (!/^vite(?:\s|$)/.test(value)) return false;
  return !/(?:^|\s)(?:--config|-c|--root)(?:\s|=|$)/.test(value);
}

/**
 * Real path of `worktreeDir/node_modules` when it is a symlink (Vercio reuses
 * the developer's dependency tree or its cache instead of installing), else null.
 */
export function linkedNodeModulesDir(worktreeDir) {
  const modules = path.join(worktreeDir, "node_modules");
  try {
    if (!fs.lstatSync(modules).isSymbolicLink()) return null;
    return fs.realpathSync(modules);
  } catch {
    return null;
  }
}

/**
 * Vite only serves files inside its `server.fs.allow` roots. When the worktree
 * reuses node_modules through a symlink, assets referenced from dependencies
 * (fonts, images, CSS...) resolve to their real path outside the worktree and
 * Vite answers 403. Write a throwaway config that loads the project's own config
 * and adds the linked dependency directory to the allow list.
 *
 * The caller must fall back to the plain dev command if this overlay cannot be
 * loaded by the project.
 */
export function writeViteConfigOverlay(worktreeDir, allowedDirs) {
  const configFile = findViteConfig(worktreeDir);
  const resolvedDirs = allowedDirs.map((dir) => path.resolve(dir));
  const lines = [
    "// Generated by Vercio for this preview worktree. Safe to delete.",
    'import { mergeConfig } from "vite";',
  ];
  if (configFile) lines.push('import baseConfig from "./' + configFile + '";');
  lines.push(
    "const allowedDirs = " + JSON.stringify(resolvedDirs) + ";",
    "export default async function vercioConfig(env) {",
    configFile
      ? '  const base = typeof baseConfig === "function" ? await baseConfig(env) : baseConfig;'
      : "  const base = {};",
    "  return mergeConfig(base || {}, {",
    "    server: { fs: { allow: [process.cwd(), ...allowedDirs] } },",
    "  });",
    "}",
    ""
  );
  fs.writeFileSync(path.join(worktreeDir, VITE_OVERLAY_FILE), lines.join("\n"));
  return VITE_OVERLAY_FILE;
}
